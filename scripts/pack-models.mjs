// Embeds assets/models/*.glb into src/room3d/models.generated.ts as base64, so models travel
// inside the editor bundle and the exported room.js (no network fetch, no extra files).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'assets/models'
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.glb')).sort() : []
const body = files.map((f) => `  ${JSON.stringify(f.slice(0, -4))}: ${JSON.stringify(readFileSync(join(dir, f)).toString('base64'))},`).join('\n')
writeFileSync(
  'src/room3d/models.generated.ts',
  `// Generated by scripts/pack-models.mjs from assets/models/*.glb. Do not edit by hand.\nexport const MODELS_B64: Record<string, string> = {${body ? `\n${body}\n` : ''}}\n`,
)
console.log(`packed ${files.length} model(s): ${files.map((f) => f.slice(0, -4)).join(', ') || '(none)'}`)
