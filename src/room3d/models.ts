import * as THREE from 'three'
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js'
import { MODELS_B64 } from './models.generated.ts'

/**
 * Optional AI-generated props (Hunyuan3D-2, made offline and embedded as base64, so there is no
 * network fetch and exported sites stay self-contained). A kind without a model, or a model that
 * fails to parse, keeps its procedural look.
 */
export type ModelSpec = { height: number; /** Largest footprint side, so it fits one floor cell. */ footprint?: number; yaw?: number; lift?: number; color: string }

export const MODEL_SPECS: Record<string, ModelSpec> = {
  // Generated by Hunyuan3D-2 (shape only; colour is applied here). Heights are in room units.
  bookcase: { height: 0.85, footprint: 0.9, yaw: 0, color: '#c9a36d' },
}

const cache = new Map<string, THREE.Group>()
let loading: Promise<void> | null = null

function b64ToBuffer(b64: string): ArrayBuffer {
  const bin = atob(b64)
  const bytes = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i)
  return bytes.buffer
}

/** Parses every embedded model once. Safe to call repeatedly. */
export function preloadModels(): Promise<void> {
  if (loading) return loading
  const loader = new GLTFLoader()
  const jobs = Object.entries(MODELS_B64).map(
    ([kind, b64]) =>
      new Promise<void>((resolve) => {
        try {
          loader.parse(
            b64ToBuffer(b64),
            '',
            (gltf) => {
              const spec = MODEL_SPECS[kind]
              const g = new THREE.Group()
              const inner = gltf.scene
              inner.traverse((c) => {
                const m = c as THREE.Mesh
                if (!m.isMesh) return
                m.castShadow = true
                m.receiveShadow = true
                m.material = new THREE.MeshStandardMaterial({
                  color: spec?.color ?? '#d9c7a8',
                  roughness: 0.7,
                  flatShading: false,
                })
              })
              // Normalise: sit on y = 0, centred, scaled to the requested height.
              const box = new THREE.Box3().setFromObject(inner)
              const size = box.getSize(new THREE.Vector3())
              const s = Math.min(
                (spec?.height ?? 0.3) / Math.max(size.y, 1e-4),
                (spec?.footprint ?? 99) / Math.max(size.x, size.z, 1e-4),
              )
              inner.scale.setScalar(s)
              const box2 = new THREE.Box3().setFromObject(inner)
              const c = box2.getCenter(new THREE.Vector3())
              inner.position.set(-c.x, -box2.min.y + (spec?.lift ?? 0), -c.z)
              inner.rotation.y = spec?.yaw ?? 0
              g.add(inner)
              cache.set(kind, g)
              resolve()
            },
            () => resolve(),
          )
        } catch {
          resolve()
        }
      }),
  )
  loading = Promise.all(jobs).then(() => undefined)
  return loading
}

/** A fresh copy of the model for a kind, or null when the procedural look should be used. */
export function modelFor(kind: string): THREE.Group | null {
  const g = cache.get(kind)
  return g ? g.clone(true) : null
}
