const DICT: Record<Lang, Record<Key, string>> = { en, zh }
const STORE_KEY = 'li-lang'

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORE_KEY)
    if (saved === 'en' || saved === 'zh') return saved
  } catch {
    /* storage may be blocked */
  }
  return typeof navigator !== 'undefined' && /^zh/i.test(navigator.language) ? 'zh' : 'en'
}

let current: Lang = detect()
const subs = new Set<() => void>()

if (typeof document !== 'undefined') document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en'

export const getLang = (): Lang => current

export function setLang(l: Lang): void {
  if (l === current) return
  current = l
  try {
    localStorage.setItem(STORE_KEY, l)
  } catch {
    /* ignore */
  }
  if (typeof document !== 'undefined') document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
  for (const f of subs) f()
}

/** Re-renders the calling component whenever the language changes. */
export function useLang(): Lang {
  const [, bump] = useState(0)
  useEffect(() => {
    const f = () => bump((n) => n + 1)
    subs.add(f)
    return () => void subs.delete(f)
  }, [])
  return current
}

export function onLangChange(f: () => void): () => void {
  subs.add(f)
  return () => void subs.delete(f)
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = DICT[current][key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

export function formatDateLocal(iso: string): string {
  return new Date(iso).toLocaleDateString(current === 'zh' ? 'zh-CN' : undefined, { year: 'numeric', month: 'short', day: 'numeric' })
}
